import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Run this after generating the Java client from the ProofState API definition.
// --source-brand adapts a differently named generated package during migration.
const repository = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const destination = path.join(repository, "src/main/java/ai/proofstate/client");
const args = process.argv.slice(2);
const refresh = args.includes("--refresh");
const brandIndex = args.indexOf("--source-brand");
const sourceBrand = brandIndex === -1 ? null : args[brandIndex + 1];

if (args.some((arg) => !["--refresh", "--source-brand", sourceBrand].includes(arg))) {
  throw new Error("Usage: node scripts/rebrand-generated.mjs [--refresh] [--source-brand NAME]");
}
if (brandIndex !== -1 && (!sourceBrand || !/^[a-z][a-z0-9]*$/i.test(sourceBrand))) {
  throw new Error("--source-brand requires an alphanumeric product name");
}

function filesUnder(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = path.join(directory, entry.name);
    return entry.isDirectory() ? filesUnder(entryPath) : entry.isFile() ? [entryPath] : [];
  });
}

function adapt(content, relativePath) {
  let result = content;
  if (sourceBrand) {
    const lower = sourceBrand.toLowerCase();
    const title = lower[0].toUpperCase() + lower.slice(1);
    result = result
      .replaceAll(sourceBrand.toUpperCase(), "PROOFSTATE")
      .replaceAll(title, "ProofState")
      .replaceAll(lower, "proofstate");
  }
  result = result
    .replace(/Use the 'pk-ps-' prefix for new keys; legacy 'pk-[a-z]{2}-' keys are also accepted\./g,
      "Keys use the 'pk-ps-' prefix.")
    .replace(/Use the 'sk-ps-' prefix for new keys; legacy 'sk-[a-z]{2}-' keys are also accepted\./g,
      "Keys use the 'sk-ps-' prefix.");

  if (relativePath.endsWith("ClientBuilder.java")) {
    result = result.replace(
      "private Environment environment;",
      'private Environment environment = Environment.custom("https://proofstate.ai");',
    );
  }

  if (relativePath.endsWith("ClientOptions.java")) {
    const pom = fs.readFileSync(path.join(repository, "pom.xml"), "utf8");
    const version = pom.match(/<artifactId>proofstate-java<\/artifactId>\s*<version>([^<]+)<\/version>/)?.[1];
    if (!version) throw new Error("Missing ProofState artifact version");
    const defaultHeaders = /this\.headers\.putAll\(new HashMap<String,String>\(\) \{\{put\("X-Fern-Language", "[^"]*"\);put\("X-Fern-SDK-Name", "[^"]*"\);put\("X-Fern-SDK-Version", "[^"]*"\);\}\}\);/;
    if (defaultHeaders.test(result)) {
      result = result.replace(
        defaultHeaders,
        'this.headers.putIfAbsent("X-ProofState-Sdk-Name", "proofstate-java");\n'
          + `    this.headers.putIfAbsent("X-ProofState-Sdk-Version", "${version}");`,
      );
    } else if (result.includes('this.headers.putIfAbsent("X-ProofState-Sdk-Name"')) {
      const brandedVersion = /this\.headers\.putIfAbsent\("X-ProofState-Sdk-Version", "[^"]*"\);/;
      if (!brandedVersion.test(result)) {
        throw new Error("The generated client version header changed unexpectedly");
      }
      result = result.replace(
        brandedVersion,
        `this.headers.putIfAbsent("X-ProofState-Sdk-Version", "${version}");`,
      );
    } else {
      throw new Error("The generated client identity headers changed unexpectedly");
    }
  }

  return result;
}

function rewriteTree(directory) {
  let changed = 0;
  for (const file of filesUnder(directory)) {
    if (!/\.(java|json)$/.test(file)) continue;
    const content = fs.readFileSync(file, "utf8");
    const adapted = adapt(content, path.relative(directory, file));
    if (adapted !== content) {
      fs.writeFileSync(file, adapted);
      changed++;
    }
  }
  return changed;
}

if (sourceBrand && !refresh) {
  const source = path.join(repository, "src/main/java/com", sourceBrand.toLowerCase(), "client");
  if (!fs.existsSync(source)) {
    throw new Error(`Missing generated client source at ${source}`);
  }
  const generated = filesUnder(source);
  if (generated.filter((file) => file.endsWith(".java")).length < 200) {
    throw new Error("The generated Java source tree is unexpectedly small");
  }
  fs.mkdirSync(destination, { recursive: true });
  for (const file of filesUnder(destination)) {
    if (file.endsWith(".java") && fs.readFileSync(file, "utf8")
      .includes("This file was auto-generated by Fern")) {
      fs.unlinkSync(file);
    }
  }
  for (const file of generated) {
    const relative = path.relative(source, file);
    const renamed = adapt(relative, relative);
    const target = path.join(destination, renamed);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.copyFileSync(file, target);
  }
  fs.rmSync(source, { recursive: true });
}

if (!fs.existsSync(destination)) throw new Error(`Missing Java client at ${destination}`);
const changed = rewriteTree(destination);
const testsChanged = rewriteTree(path.join(repository, "src/test/java/ai/proofstate/client"));
console.log(`Adapted ${changed} generated files and ${testsChanged} test files`);
